// templateNeedles are assembled at run time so this test file is not itself a hit.
func templateNeedles() []string {
	lower := "x" + "y" + "z"
	return []string{lower, "X" + "yz", "pulumi/pulumi-" + lower}
}

func brandNeedle() string { return "gno" + "sis" }

func repoRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatalf("resolve repo root: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, ".git")); err != nil {
		t.Fatalf("repo root %s has no .git: %v", root, err)
	}
	return root
}

func git(t *testing.T, dir string, args ...string) (string, error) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.Output()
	return strings.TrimSpace(string(out)), err
}

func mustGit(t *testing.T, dir string, args ...string) string {
	t.Helper()
	out, err := git(t, dir, args...)
	if err != nil {
		t.Fatalf("git %s in %s: %v", strings.Join(args, " "), dir, err)
	}
	return out
}

// repoFiles lists every path this repo tracks or would track. Submodule contents
// are excluded by git itself: a submodule is one gitlink entry, not a file tree.
func repoFiles(t *testing.T) []string {
	t.Helper()
	root := repoRoot(t)
	out := mustGit(t, root, "ls-files", "--cached", "--others", "--exclude-standard")
	if out == "" {
		t.Fatal("git ls-files listed no files")
	}
	var files []string
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		info, err := os.Stat(filepath.Join(root, line))
		if err != nil || info.IsDir() {
			continue
		}
		files = append(files, line)
	}
	return files
}

func TestNoAutogeneratedFilesRemain(t *testing.T) {
	root := repoRoot(t)
	for _, rel := range repoFiles(t) {
		body, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			t.Fatalf("read %s: %v", rel, err)
		}
		first := body
		if i := strings.IndexByte(string(body), '\n'); i >= 0 {
			first = body[:i]
		}
		if strings.Contains(string(first), generatedMarker) {
			t.Errorf("%s: first line still carries the ci-mgmt generated marker: %s", rel, first)
		}
	}
}

func TestCIMgmtArtifactsDeleted(t *testing.T) {
	root := repoRoot(t)
	for _, artifact := range ciMgmtArtifacts {
		if _, err := os.Lstat(filepath.Join(root, artifact)); !os.IsNotExist(err) {
			t.Errorf("%s still exists (err=%v); the fork deletes it", artifact, err)
		}
	}
	for _, rel := range repoFiles(t) {
		for _, artifact := range ciMgmtArtifacts {
			if rel == artifact || strings.HasPrefix(rel, artifact+"/") {
				t.Errorf("%s is still tracked; the fork deletes %s", rel, artifact)
			}
		}
	}
}

