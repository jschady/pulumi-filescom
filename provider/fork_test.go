// assertNeedlesAbsent greps repo content. go.sum is checked on its module-path
// field only: its base64 hashes produce chance matches that mean nothing.
func assertNeedlesAbsent(t *testing.T, needles []string, foldCase bool) {
	t.Helper()
	root := repoRoot(t)
	for _, rel := range repoFiles(t) {
		haystacks := []string{rel}
		body, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			t.Fatalf("read %s: %v", rel, err)
		}
		if filepath.Base(rel) == "go.sum" {
			for _, line := range strings.Split(string(body), "\n") {
				if fields := strings.Fields(line); len(fields) > 0 {
					haystacks = append(haystacks, fields[0])
				}
			}
		} else {
			haystacks = append(haystacks, string(body))
		}
		for _, haystack := range haystacks {
			if foldCase {
				haystack = strings.ToLower(haystack)
			}
			for _, needle := range needles {
				if foldCase {
					needle = strings.ToLower(needle)
				}
				if strings.Contains(haystack, needle) {
					t.Errorf("%s still references %q", rel, needle)
					break
				}
			}
		}
	}
}

// TestNoBrandInGitMetadata guards what file content cannot: an author, committer,
// or amended-away reflog entry carrying the brand this repository never names.
func TestNoBrandInGitMetadata(t *testing.T) {
	root := repoRoot(t)
	needle := strings.ToLower(brandNeedle())

	for _, line := range strings.Split(mustGit(t, root, "log", "--all", "--format=%an <%ae>%n%cn <%ce>"), "\n") {
		if strings.Contains(strings.ToLower(line), needle) {
			t.Errorf("commit identity %q references %q", strings.TrimSpace(line), brandNeedle())
		}
	}

	logs := filepath.Join(root, ".git", "logs")
	if _, err := os.Stat(logs); os.IsNotExist(err) {
		return
	}
	err := filepath.WalkDir(logs, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		//nolint:gosec // G122: reads this repo's own .git/logs; no untrusted symlink to race.
		body, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if strings.Contains(strings.ToLower(string(body)), needle) {
			rel, _ := filepath.Rel(root, p)
			t.Errorf("%s references %q; expire the reflog so no brand identity survives", rel, brandNeedle())
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", logs, err)
	}
}

// shimUpstreamVersion answers the upstream version provider/shim/go.mod requires. The shim is
// the module that names the upstream provider directly, so its require line is the version the
// gitlink, provider/go.mod, and examples/go.mod follow.
func shimUpstreamVersion(t *testing.T) string {
	t.Helper()
	return pinsGoModRequire(t, "provider/shim/go.mod", "github.com/"+upstreamRepoSlug)
}

func TestUpstreamSubmodulePinnedToTag(t *testing.T) {
	root := repoRoot(t)

	modules, err := os.ReadFile(filepath.Join(root, ".gitmodules"))
	if err != nil {
		t.Fatalf("read .gitmodules: %v", err)
	}
	if !strings.Contains(string(modules), upstreamRepoSlug) {
		t.Errorf(".gitmodules does not point at %s:\n%s", upstreamRepoSlug, modules)
	}

	// The upstream version has 4 copies: the gitlink, provider/shim/go.mod, and the indirect
	// requires of provider/go.mod and examples/go.mod. A release that moves some of them builds
	// the provider against one upstream and the examples against another.
	upstreamTag := shimUpstreamVersion(t)
	for _, path := range []string{"provider/go.mod", "examples/go.mod"} {
		if pin := pinsGoModRequire(t, path, "github.com/"+upstreamRepoSlug); pin != upstreamTag {
			t.Errorf("%s pins %s, and provider/shim/go.mod pins %s; move the 4 pins together",
				path, pin, upstreamTag)
		}
	}

	entry := mustGit(t, root, "ls-files", "--stage", "upstream")
	fields := strings.Fields(entry)
	if len(fields) < 2 {
		t.Fatalf("no staged upstream entry; git ls-files --stage upstream gave %q", entry)
	}
	if fields[0] != "160000" {
		t.Fatalf("upstream has mode %s, want 160000 (a submodule gitlink)", fields[0])
	}
	gitlink := fields[1]

	sub := filepath.Join(root, "upstream")
	tagCommit, err := git(t, sub, "rev-parse", upstreamTag+"^{commit}")
	if err != nil {
		t.Fatalf("tag %s not found in the upstream submodule: %v", upstreamTag, err)
	}
	if gitlink != tagCommit {
		t.Errorf("gitlink is %s, want %s (tag %s)", gitlink, tagCommit, upstreamTag)
	}
	if head := mustGit(t, sub, "rev-parse", "HEAD"); head != tagCommit {
		t.Errorf("upstream HEAD is %s, want %s (tag %s)", head, tagCommit, upstreamTag)
	}
}
